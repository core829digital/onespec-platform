// Writes src/demo/convex-modules.generated.ts: the lazy module map convex-test needs to run the real Convex functions in the browser
// (the public demo of the platform). Re-run after adding a Convex module:  node scripts/gen-demo-modules.mjs
import { readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = new URL("../convex/", import.meta.url).pathname;
// Not needed by the demo: sign-in (the demo user is always signed in), HTTP routes, crons, e-mail providers, seed/migration tools.
const EXCLUDE = new Set(["auth.ts", "auth.config.ts", "http.ts", "crons.ts", "ResendOTP.ts", "ResendPasswordReset.ts", "seed.ts", "migrations.ts"]);

function walk(dir) {
  return readdirSync(dir).flatMap((f) => {
    const p = join(dir, f);
    if (statSync(p).isDirectory()) return f === "http" || f === "node_modules" ? [] : walk(p);
    return p.endsWith(".ts") && !p.endsWith(".d.ts") && !p.includes(".test.") ? [p] : [];
  });
}

const files = walk(root)
  .map((p) => relative(root, p).split("\\").join("/"))
  .filter((p) => !EXCLUDE.has(p) && !p.startsWith("_generated/"))
  .sort();

const lines = [
  "/* eslint-disable */",
  "// GENERATED by scripts/gen-demo-modules.mjs — do not edit.",
  "// One lazy import per Convex module: a module is only downloaded when the demo first calls a function in it.",
  "type Loader = () => Promise<unknown>;",
  "export const DEMO_CONVEX_MODULES: Record<string, Loader> = {",
  // convex-test finds the root of the functions from a path containing `_generated`.
  `  "../convex/_generated/api.js": () => import("../../convex/_generated/api"),`,
  ...files.map((f) => `  "../convex/${f}": () => import("../../convex/${f.replace(/\.ts$/, "")}"),`),
  "};",
  "",
];
writeFileSync(new URL("../src/demo/convex-modules.generated.ts", import.meta.url), lines.join("\n"));
console.log(`demo module map: ${files.length} modules`);
